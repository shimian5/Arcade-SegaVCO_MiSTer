// Turbo player-car channel (sheets D-8/11 and D-9/11).
//
//   D8 source/control: ACC(0-5) -> IC34/C110 speed ladder (64-code Thevenin
//   targets).  The MYCAR carrier is the IC6/C5 tone cell plus the IC6/C18+C19
//   sub cell through D7/D13, R79 and C76 (turbo_playercar_mycarsource.sv).  The
//   IC3/IC5/IC7 transient model (turbo_playercar_d8_transient.sv) only supplies
//   the MY CAR CONT / BSEL1 control side.  The hand-written "4391/2" blocks are
//   MB4391M dual-MC3340 VCAs.
//
//   D9 control/VCA: IC41 (74LS139) BSEL decoder selects exactly one of
//   BCONT0/1/2.  Each BCONT is a gated one-pole gain toward FULL (selected) or
//   MUTE (unselected).  BCONT0 drives the IC19-A/B VCA pair (MYCARQ.F/FM,
//   MYCARQ.W); BCONT1 drives IC18/IC28-upper (MYCAR1.F/FM, MYCAR1.W); BCONT2
//   drives IC28-lower (MYCAR.F/W/M via the R219/R220 loaded-feed split).  The
//   per-tap loading resistors of IC19/IC18 are not on the recovered sheets, so
//   MYCARQ.F/W (and MYCAR1.F/W) share one VCA product each.
//
//   SLF: switched by /MYCAR OFF (mycar_off_n, asserted at BSEL==3) through the
//   IC30/C108 W-bus transient.
//
// MULTIPLIER SHARING: every multiply (ladder smoothing, three BCONT gain
// updates, VCA products, two output DC-blocks; eleven ops per sample) is
// serialized through one shared_mul_lane via u_playercar_seq, the same
// P_IDLE/P_REQ/P_WAIT/P_READY idiom as turbo_crash_chan.sv's preamp sequencer.
// No two multiplies are chained combinationally; every op's operands and result
// are registered.
//
// DC-BLOCKING: the VCA outputs are DC-referenced node voltages; their output
// coupling caps (C114/C113/C112/C107/C69/C72/C66/C57/C61) are not modelled
// individually.  Two one-pole DC-blockers (~20 Hz) on the final F and W bus
// sums stand in for them so the audio taps are AC-centred.
