// being sent to the HDMI framebuffer (~no_rotate, same signal screen_rotate
// below uses) -- otherwise the scaler keeps stretching the now-portrait
// image into the landscape 4:3 declared for Buck Rogers, matching
// Arcade-DonkeyKong_MiSTer's identical VIDEO_ARX/ARY swap pattern for its
// own rotated cabinet. "Full Screen"/[ARC1]/[ARC2] (ar!=0) are explicit
