`include "build_id.v"
localparam CONF_STR = {
	"SegaVCO;;",
	"-;",
	"O[122:121],Aspect ratio,Original,Full Screen,[ARC1],[ARC2];",
	// Turbo's native raster is portrait (MAME lists turbo as ROT270; Buck
	// Rogers/buckrogn are ROT0). This option only affects the HDMI
	// framebuffer-scaler path (screen_rotate below writes a rotated copy
	// to DDRAM); VGA output is always the raw, unrotated picture, matching
	// a genuinely rotated cabinet monitor wired via VGA. No effect on Buck
	// Rogers (forced off below regardless of this bit).
	// H0 hides these two Turbo-only entries when Buck Rogers is loaded
	// (status_menumask[0] driven by ~mod_turbo below) -- no point showing
	// Turbo's rotate/steering options on a game that ignores both bits.
	"H0O[6],Rotate HDMI (Turbo),Auto,Off;",
	"H0O[10],D-Pad Steering (Turbo),Velocity,Position;",
	"-;",
	// DIP switch VALUES are not declared here -- per MiSTer arcade-core
	// convention (mister-devel MkDocs_MiSTer, developer/mra) they live in
	// each game's MRA <switches>/<dip> elements, sent to the core over
	// ioctl_index==254 as up to 8 raw bytes (sw[0..7] below) -- NOT baked
	// into CONF_STR as O/P1O/P2O options driven by `status`. This also
	// fixes DIP settings not persisting: MRA-sourced DIPs are saved/
	// restored per-game by the OSD, where CONF_STR status bits are one
	// core-wide blob that doesn't survive switching games. See dsw1/dsw2/
	// turbo_dsw1/turbo_dsw2/turbo_dsw3 below.
	//
	// The literal "DIP;" entry below IS still required, though: confirmed
	// against Darius_MiSTer/Template.sv (a working reference core) that
	// this is the placeholder that tells the OSD to render the MRA-sourced
	// DIP switches page at this position in the menu -- omitting it (the
	// original mistake here) leaves the OSD with no DIP page at all, MRA
	// <switches> or not. Buck Rogers and Turbo ship different <switches>
	// blocks in their own .mra files (mra/buckrog.mra, mra/buckrogn.mra,
	// mra/turbo.mra, generated by tools/gen_mra.py), so no H1/h1
	// page-hiding is needed the way the old CONF_STR-embedded DIPs required.
	"DIP;",
	"-;",
	// T[0]/R[0] both on status bit 0, matching Darius_MiSTer/Template.sv AND
	// this user's own SuperOffRoad_MiSTer/SuperOffRoad.sv verbatim -- do not
	// change this again without hardware evidence specific to THIS core.
	//
	// MUST come before J1: J1 is a non-OSD directive (joystick button-name
	// binding, not a menu entry) and per mister-devel's CONF_STR reference,
	// non-OSD directives belong at the bottom of CONF_STR, after all real
	// menu entries. Both reference cores above follow this -- T[0]/R[0]
	// precede J1 in both -- and this core had it backwards (J1 before the
	// reset entries), which is consistent with T[0] not triggering and R[0]
	// not being recognized as the close-OSD variant.
	"T[0],Reset;",
	"R[0],Reset and close OSD;",
	// Only the buttons the game actually has -- no placeholder entries. Start/
	// Coin are the shared bit positions (joystick_0/1[7]/[8]) both games use,
	// and P2 takes its own controller's copies of the SAME bit positions, so
	// P2 start and P2 coin never land on P1's pad. Turbo's own Gear Shift/
	// Pedal are appended at the end rather than reusing Buck's Fire/Accel
	// bits, so neither game's button list disturbs the other's bit positions.
	// Names must match <buttons names="..."> in mra/*.mra.
	"J1,Fire,Accel Fast,Accel Slow,Start,Coin,Gear Shift,Pedal;",
	"v,0;", // [optional] config version 0-99.
	        // If CONF_STR options are changed in incompatible way, then change version number too,
			  // so all options will get default values on first start.
	"V,v",`BUILD_DATE
};

