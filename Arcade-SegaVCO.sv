// Game strap: ioctl_index 1 is the mod byte MRA part gen_mra.py emits
// after every game's ROM regions (00 = Buck Rogers, 01 = Turbo). One RBF,
// selected at ROM-load time -- see docs/WORKPLAN_TURBO_GRAPHICS.md Step 1.
reg [7:0] mod_game;
always @(posedge clk_sys) if (ioctl_wr && ioctl_index == 16'd1) mod_game <= ioctl_dout;
wire mod_turbo = mod_game[0];

// DIP switches, MRA-sourced (mister-devel MkDocs_MiSTer, developer/mra):
// each game's .mra <switches> block streams up to 8 raw bytes over
// ioctl_index==254, addressed by ioctl_addr[2:0]. sw[0] = DSW1, sw[1] =
// DSW2, sw[2] = DSW3, matching the physical DIP bank numbering in
// docs/reference/turbo.cpp -- so dsw1/dsw2/turbo_dsw1/turbo_dsw2/
// turbo_dsw3 below are the raw bytes verbatim, no bit-inversion or
// reordering needed (the MRA's <dip ids="..."> order already encodes the
// correct raw value for each menu choice).
reg [7:0] sw[0:7];
always @(posedge clk_sys) if (ioctl_wr && ioctl_index == 16'd254) sw[ioctl_addr[2:0]] <= ioctl_dout;

// IN0/IN1/DSW1/DSW2 -- docs/PLAN.md phase 1 CPU/memory table, buckrog
// INPUT_PORTS_START in docs/reference/turbo.cpp. Joystick bit convention:
// [0]=Right [1]=Left [2]=Down [3]=Up are MiSTer's standard D-pad bits; the
// named buttons then start at [4] in "J1,..." order, so [4]=Fire,
// [5]=Accel Fast, [6]=Accel Slow, [7]=Start, [8]=Coin. All active-low
// (idle = 1), matching MAME's ACTIVE_LOW convention.
//
// P2's start and coin are read from joystick_1 at the SAME bit positions as
// P1's, which is the MiSTer convention -- taking them from spare joystick_0
// bits instead would put P2's start and coin on P1's controller.
//
// SERVICE1 (IN1 bit 5) and the TEST/service-mode line (IN1 bit 4) are tied
// inactive on purpose: neither had any observable effect in play, and a
// mapped button that does nothing is worse than no button. They are real
// hardware inputs (schematic sheet 4: I15=SERVICE, I14=TEST) and can be
// wired later if a use for them turns up.
//
// in0[5:4] are ACC.LO/ACC.HI (schematic sheet 4, PDF p32: two discrete
// opto-isolated lines on the control connector). The same two wires serve
// both accel modes -- SW2:2 only selects how the GAME reads them: fast/slow
// buttons in Button mode (the factory setting, wired here), or an inverted
// 2-bit Gray code from the pedal's opto pair in Pedal mode. No analog pedal
// source is wired, so selecting Pedal in the OSD leaves the throttle dead.
wire [7:0] in0 = {~joystick_0[3], ~joystick_0[2], ~joystick_0[6], ~joystick_0[5], ~joystick_1[7], 3'b111};
// NOTE in1[1:0]: MAME's IN1 is bit 0x01 = JOYSTICK_LEFT, bit 0x02 =
// JOYSTICK_RIGHT (turbo.cpp INPUT_PORTS_START(buckrog)), which is the
// OPPOSITE order from the MiSTer joystick convention above ([0]=Right,
// [1]=Left). These two bits were previously wired straight through in
// index order, which transposed the steering axis -- the ship (and with
// it the starfield's lateral sweep) banked the wrong way for a given
// stick direction. Cross them explicitly; do not "simplify" this back to
// [1],[0] order.
wire [7:0] in1 = {~joystick_0[8], ~joystick_1[8], 1'b1, 1'b1, ~joystick_0[7], ~joystick_0[4], ~joystick_0[0], ~joystick_0[1]};

// DSW assembly. Bit positions are buckrog's DSW1/DSW2 as read through
// port_2_r/port_3_r (the 4-bit bitswaps live in rtl/segavco.v, not here).
// Raw bytes straight from the MRA (see sw[] above) -- mra/buckrog.mra and
// mra/buckrogn.mra's <switches default="C0,92"> already encode the factory
// DSW1/DSW2 defaults (docs/reference/turbo.cpp), so no inversion is needed
// here the way the old status-bit CONF_STR options required.
wire [7:0] dsw1 = sw[0];
wire [7:0] dsw2 = sw[1];

// ------------------------------------------------------------------
// Turbo IN0/DSW1/DSW2/DSW3 and controls (docs/WORKPLAN_TURBO_GRAPHICS.md
// Step 7). turbo.cpp's IN0: bits[1:0] = pedal (inverted 2-bit Gray code),
// bit2 = gear shift (active-high, PORT_TOGGLE), bit3 = start1 (active-low),
// bit4 = service mode, bit5 = service1, bit6 = coin2, bit7 = coin1.
// Reuses Buck's Start/Coin bit positions (joystick_0[7]/[8]) so both games'
// buttons stay physically consistent; Gear Shift/Pedal are the two NEW J1
// entries appended above.
// ------------------------------------------------------------------
wire pedal_btn = joystick_0[10];
wire [7:0] pedal_raw = pedal_btn ? 8'hFF : 8'h00;
wire [7:0] pedal_gray = (pedal_raw >> 6) ^ (pedal_raw >> 7) ^ 8'h03;

// PORT_TOGGLE: the reported bit flips on each press (rising edge), not a
// plain pass-through -- matches turbo.cpp's gear shift lever, which stays
// in whichever gear it was last shifted to.
reg gear_toggle;
reg gear_btn_d;
always @(posedge clk_sys) begin
	gear_btn_d <= joystick_0[9];
	if (joystick_0[9] && !gear_btn_d) gear_toggle <= ~gear_toggle;
end

// bit6 (coin2) was previously ~joystick_1[5] (P2's Accel Fast button) --
// wrong bit entirely. Matches Buck's own in1[6] convention (~joystick_1[8],
// the same physical P2 coin button both games' cabinets share).
wire [7:0] turbo_in0 = {~joystick_0[8], ~joystick_1[8], 1'b1, 1'b1,
                         ~joystick_0[7], gear_toggle, pedal_gray[1:0]};

// DSW1/DSW2/DSW3 assembly. Raw bytes straight from the MRA (see sw[]
// above) -- mra/turbo.mra's <switches default="FB,FF,30"> already encodes
// the factory DSW1/DSW2/DSW3 defaults (docs/reference/turbo.cpp), so no
// inversion or reordering is needed the way the old status-bit CONF_STR
// options required.
wire [7:0] turbo_dsw1 = sw[0];
wire [7:0] turbo_dsw2 = sw[1];
wire [7:0] turbo_dsw3 = sw[2];

// Steering: turbo_state::analog_r() returns a DELTA (dial - last_analog),
// not an absolute position -- see rtl/io/steering_input.sv's header. The
// delta computation itself (the last_analog snapshot register, reset by
// writes to b800-bfff) lives in segavco.v, alongside the PPI3 port A read
// it feeds; this module only produces the free-running dial position.
reg vblank_d;
always @(posedge clk_sys) vblank_d <= VBlank;
wire ce_frame = VBlank & ~vblank_d;

// Tuned against the real Turbo steering mechanism, not just MAME's DIAL port:
// the schematic's LS191 counter is a x1 quadrature relative encoder (no HW
// accel/spring), and the photographed wheel-shaft gearing (~5:1) + encoder
// disk (~40 slots) puts one hardware count at roughly 45 degrees of wheel
// rotation -- i.e. the observed real-cabinet "~1/4 turn = ~1 car width"
// correction is only ~2 counts. RAMP_STEP=2/VEL_MAX=6 (post >>>1 shift) so
// the velocity ramp actually ramps instead of jumping straight to its
// ceiling: a 1-frame tap yields 1 count, climbing 1/2/3 over the first
// three held frames and capping at 3 counts/frame thereafter -- small taps
// stay small, and the 3-count/frame sustained ceiling (~135 degrees/frame)
// avoids constantly injecting the ~180-degree-plus swings a higher ceiling
// would imply, while still allowing full wheel rotation over a longer
// hold. POS_MAX=48 matches: the spring-return position mode's contribution
// (deflect>>>4) also tops out at 3 counts/frame, down from ~15 at the
// module's original default. Position mode remains a convenience
// alternative, not a cabinet-accurate model -- the real wheel has no
// spring return. ANALOG_SHIFT split out to 5 (SHIFT stays 4 for the dpad)
// so full analog-stick deflection (127>>>5 = 3 counts/frame) lines up with
// the same 3-count/frame ceiling as the dpad's sustained hold and the
// initial tap stays at 1 -- one coherent ceiling across all three digital
// input paths for the first hardware test.
wire [7:0] turbo_dial;
steering_input #(
	.RAMP_STEP(9'sd2), .VEL_MAX(9'sd6), .POS_MAX(9'sd48), .SHIFT(4), .ANALOG_SHIFT(5)
) u_steering
(
	.clk_sys(clk_sys), .reset(reset), .ce_frame(ce_frame),
	.dpad_pos_mode(status[10]), // OSD "D-Pad Steering": 0 = velocity ramp (default), 1 = position w/ spring-return
	.analog_x(joystick_l_analog_0[7:0]),
	.dpad_left(joystick_0[1]), .dpad_right(joystick_0[0]),
	.spinner(spinner_0),
	.wheel_pos(turbo_dial)
);

